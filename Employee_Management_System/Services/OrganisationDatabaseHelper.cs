using Microsoft.Data.SqlClient;

namespace Employee_Management_System.Services
{
    /// <summary>
    /// Single place that decides which SQL Server database belongs to an
    /// organisation. The database name is ALWAYS derived on the server from the
    /// integer Organisation Code - it is never read from the browser.
    ///
    ///   Code 1  -> PayData_STM
    ///   Code &gt;1 -> PayData_{Code}
    /// </summary>
    public static class OrganisationDatabaseHelper
    {
        public const string MasterDatabaseName = "PayData_STM";

        public static string GetDatabaseName(int organisationCode)
        {
            if (organisationCode <= 0)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(organisationCode),
                    "Organisation Code must be greater than zero.");
            }

            return organisationCode == 1
                ? MasterDatabaseName
                : $"PayData_{organisationCode}";
        }

        /// <summary>
        /// Builds the connection string of an organisation database from the
        /// existing DefaultConnection (server, authentication, options are kept;
        /// only the database is replaced).
        /// </summary>
        public static string BuildConnectionString(
            string baseConnectionString,
            int organisationCode)
        {
            return BuildConnectionString(
                baseConnectionString,
                GetDatabaseName(organisationCode));
        }

        public static string BuildConnectionString(
            string baseConnectionString,
            string databaseName)
        {
            if (string.IsNullOrWhiteSpace(baseConnectionString))
            {
                throw new InvalidOperationException(
                    "DefaultConnection is not configured in appsettings.json.");
            }

            var builder = new SqlConnectionStringBuilder(baseConnectionString)
            {
                InitialCatalog = databaseName
            };

            return builder.ConnectionString;
        }

        /// <summary>
        /// Quotes an identifier for use in dynamic T-SQL (same rules as
        /// QUOTENAME). Database names are generated by this class, but quoting
        /// is still applied as defence in depth.
        /// </summary>
        public static string QuoteName(string identifier)
        {
            return "[" + identifier.Replace("]", "]]") + "]";
        }
    }
}